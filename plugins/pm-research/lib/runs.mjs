/**
 * Research runs: one topic, one decision, one folder. The stage of a run is derived from what exists on disk
 * (brief, evidence, verified claims, report, after-action), so it cannot drift from reality or be skipped by assertion.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { CONFIG_NAME, atomicWrite, clip, ensureGlobal, fail, findProject, gpath, listRuns, loadRun, oneLine, readJsonl, requireProject, runDir, saveRun, template, today, validTopic } from './store.mjs';
import { ledgerStats } from './ledger.mjs';
import { errorCount, lintRun, section } from './lint.mjs';
import { loadPredictions } from './calibration.mjs';
import { recall } from './lessons.mjs';

export function init({ opt, cwd, env }) {
  const file = join(cwd, CONFIG_NAME);
  if (existsSync(file) && !opt.force) fail(`${CONFIG_NAME} already exists here. Edit it directly, or pass --force to overwrite.`);
  const reports = opt.reports && opt.reports !== true ? opt.reports : 'docs/research';
  const cfg = {
    project: opt.name && opt.name !== true ? opt.name : cwd.split('/').filter(Boolean).at(-1),
    reports_dir: reports,
    work_dir: opt.work && opt.work !== true ? opt.work : `${reports}/_work`,
    refresh_days: Number(opt['refresh-days'] ?? 60),
    language: opt.language && opt.language !== true ? opt.language : 'en',
    private_terms: [],
  };
  if (opt.context && opt.context !== true) cfg.context_file = opt.context;
  writeFileSync(file, `${JSON.stringify(cfg, null, 2)}\n`);
  const project = findProject(cwd);
  mkdirSync(project.workDir, { recursive: true });
  writeIndex(project);
  console.log(`wrote ${CONFIG_NAME} · reports in ${cfg.reports_dir}/ · working files in ${cfg.work_dir}/ · shared memory in ${ensureGlobal(env)}`);
}

function writeIndex(project) {
  const runs = listRuns(project);
  const rows = runs.map((r) => `| ${r.topic} | ${r.status} | ${r.created} | ${clip(r.decision, 90).replace(/\|/g, '/')} | ${existsSync(resolve(project.root, r.report)) ? r.report : '—'} |`);
  atomicWrite(join(project.workDir, 'index.md'), `# Research runs\n\nGenerated by \`pmr\`. Do not edit by hand.\n\n| Topic | Status | Started | Decision | Report |\n| --- | --- | --- | --- | --- |\n${rows.join('\n')}${rows.length ? '\n' : ''}`);
}

export function runStart(ctx) {
  const { pos, opt, cwd, env } = ctx;
  const project = requireProject(cwd);
  const topic = validTopic(pos[0]);
  const decision = oneLine(opt.decision === true ? '' : opt.decision) || fail('Missing --decision: the decision this research must inform, in one sentence. If no decision depends on it, it is not worth researching yet.');
  const door = opt.door ?? 'two-way';
  if (!['one-way', 'two-way'].includes(door)) fail('--door is one-way (hard to reverse) or two-way (cheap to reverse).');
  const depth = opt.depth ?? (door === 'one-way' ? 'deep' : 'standard');
  if (!['quick', 'standard', 'deep'].includes(depth)) fail('--depth is quick, standard or deep.');
  const dir = runDir(project, topic);
  if (existsSync(join(dir, 'run.json'))) fail(`Run "${topic}" already exists (${relative(cwd, dir)}). Continue it, or pick another topic slug.`);
  mkdirSync(dir, { recursive: true });
  const created = today(env);
  const run = { topic, decision, door, depth, status: 'open', created, closed: null, report: relative(project.root, join(project.reportsDir, `${topic}-${created.slice(0, 7)}.md`)) };
  saveRun(project, run);
  writeFileSync(join(dir, 'brief.md'), template('research-plan', 'brief.md', { topic, decision, door, depth, date: created }));
  writeIndex(project);
  console.log(`started ${topic} (${depth}, ${door} door)\nbrief:  ${relative(cwd, join(dir, 'brief.md'))}\nreport: ${relative(cwd, resolve(project.root, run.report))} (not written yet)`);
  recall({ ...ctx, opt: { skill: 'research-plan', topic: `${topic.replace(/-/g, ' ')} ${decision}`, exclude: topic } });
}

/** Everything `status`, `close` and the hooks need to know about one run. */
export function runState(project, run, env) {
  const dir = runDir(project, run.topic);
  const has = (name) => existsSync(join(dir, name));
  const stats = ledgerStats(project, run.topic);
  const lint = lintRun(project, run, { strict: false });
  const strict = lintRun(project, run, { strict: true });
  const predictions = loadPredictions(env).filter((p) => p.project === project.name && p.topic === run.topic);
  const reportPath = resolve(project.root, run.report);
  const report = existsSync(reportPath);
  const briefText = has('brief.md') ? readFileSync(join(dir, 'brief.md'), 'utf8') : '';
  const unverified = stats.byStatus.unverified ?? 0;
  let next;
  if (/\bTODO\b/.test(briefText)) next = 'finish the brief (research-plan skill): questions, hypotheses, source plan, stop rule';
  else if (!stats.evidence) next = 'collect evidence (deep-research skill): scouts return rows, record them with `pmr evidence import`';
  else if (!stats.claims) next = 'write the claims the evidence supports: `pmr claim import`';
  else if (unverified) next = `verify ${unverified} claim(s) one claim-source pair at a time (claim-verifier agent), then \`pmr claim verify\``;
  else if (!report) next = `write the report at ${run.report} from verified claims only`;
  else if (errorCount(strict)) next = `fix ${errorCount(strict)} lint error(s): \`pmr lint ${run.topic} --strict\``;
  else if (!predictions.length) next = 'record what the recommendation predicts: `pmr predict add`';
  else if (!has('after-action.md')) next = `write the after-action: \`pmr run retro ${run.topic}\``;
  else next = `close it: \`pmr run close ${run.topic}\``;
  return { dir, stats, lint, strict, predictions, report, artefacts: { brief: has('brief.md'), options: has('options.md'), plan: has('plan.md'), afterAction: has('after-action.md'), report }, next };
}

function describe(project, run, env) {
  const s = runState(project, run, env);
  const by = (obj) => Object.entries(obj).map(([k, v]) => `${v} ${k}`).join(', ') || 'none';
  const present = Object.entries(s.artefacts).filter(([, v]) => v).map(([k]) => k).join(', ') || 'none';
  return [
    `${run.topic} [${run.status}] ${run.depth}, ${run.door} door, started ${run.created}`,
    `decision: ${run.decision}`,
    `evidence: ${s.stats.evidence} (${by(s.stats.byTier)}) · claims: ${s.stats.claims} (${by(s.stats.byStatus)})${s.stats.failRate === null ? '' : ` · failed verification: ${Math.round(s.stats.failRate * 100)}%`}`,
    `artefacts: ${present} · predictions: ${s.predictions.length} · lint errors: ${errorCount(s.strict)}`,
    ...(run.status === 'open' ? [`next: ${s.next}`] : []),
  ];
}

export function runStatus({ pos, cwd, env }) {
  const project = requireProject(cwd);
  if (pos[0]) { console.log(describe(project, loadRun(project, pos[0]), env).join('\n')); return; }
  const open = listRuns(project).filter((r) => r.status === 'open');
  if (!open.length) { console.log('no open research runs'); return; }
  console.log(open.map((r) => describe(project, r, env).join('\n')).join('\n\n'));
}

export function runList({ cwd }) {
  const project = requireProject(cwd);
  const runs = listRuns(project);
  if (!runs.length) { console.log('no research runs yet'); return; }
  for (const r of runs) console.log(`${r.topic} [${r.status}] ${r.created} — ${clip(r.decision, 100)}`);
}

function mistakesOf(project, topic, env) { return readJsonl(gpath('mistakes.jsonl', env)).filter((m) => m.project === project.name && m.topic === topic); }

/** Creates the after-action file with the measured part filled in. The judgement part is left for the author. */
export function runRetro({ pos, cwd, env }) {
  const project = requireProject(cwd);
  const run = loadRun(project, pos[0]);
  const s = runState(project, run, env);
  const mistakes = mistakesOf(project, run.topic, env);
  const count = (k) => s.stats.byStatus[k] ?? 0;
  const facts = [
    `- Evidence rows: ${s.stats.evidence} (${Object.entries(s.stats.byTier).map(([k, v]) => `${v} ${k}`).join(', ') || 'none'}); never cited by a claim: ${s.stats.unusedEvidence.length}`,
    `- Claims: ${s.stats.claims}; supported ${count('supported')}, partial ${count('partial')}, refuted ${count('refuted')}, contested ${count('contested')}, unreachable ${count('unreachable')}, unverified ${count('unverified')}, open questions ${count('open')}`,
    `- Claims that failed verification: ${s.stats.failRate === null ? 'n/a' : `${Math.round(s.stats.failRate * 100)}%`}; backed by an official or primary source: ${s.stats.confirmed}`,
    `- Mistakes logged: ${mistakes.length ? mistakes.map((m) => `${m.id}${m.lesson ? ` → ${m.lesson}` : ' (no lesson yet)'}`).join(', ') : 'none'}`,
    `- Predictions: ${s.predictions.length ? s.predictions.map((p) => `${p.id} ${Math.round(p.p * 100)}% by ${p.due}`).join(', ') : 'none'}`,
  ].join('\n');
  const file = join(s.dir, 'after-action.md');
  if (existsSync(file)) { console.log(`after-action already exists: ${relative(cwd, file)}\nCurrent numbers:\n${facts}`); return; }
  writeFileSync(file, template('research-retro', 'after-action.md', { topic: run.topic, date: today(env), decision: run.decision, facts }));
  console.log(`wrote ${relative(cwd, file)}\n${facts}\nFill in the judgement sections, then \`pmr run close ${run.topic}\`.`);
}

export function runClose({ pos, cwd, env }) {
  const project = requireProject(cwd);
  const run = loadRun(project, pos[0]);
  if (run.status === 'closed') fail(`${run.topic} is already closed.`);
  const s = runState(project, run, env);
  const blockers = [];
  if (!s.report) blockers.push(`no report at ${run.report}`);
  for (const r of s.strict) for (const issue of r.issues.filter((i) => i.startsWith('error'))) blockers.push(`${r.file}: ${issue.replace(/^error: /, '')}`);
  if (!s.predictions.length) blockers.push('no prediction recorded for this run. A recommendation that predicts nothing cannot be checked later: `pmr predict add --topic <topic> …`');
  if (!s.artefacts.afterAction) blockers.push(`no after-action. Run \`pmr run retro ${run.topic}\` and fill it in`);
  else {
    const text = readFileSync(join(s.dir, 'after-action.md'), 'utf8');
    const open = mistakesOf(project, run.topic, env).filter((m) => !m.lesson);
    if (open.length) blockers.push(`mistake(s) ${open.map((m) => m.id).join(', ')} have no lesson. Distil each one or link it to an existing lesson with \`pmr lesson hit <L-id> --from <M-id>\``);
    const lessons = section(text, /^lessons\b/i) ?? '';
    if (!/L-\d{3}/.test(lessons) && !/\bnone\b/i.test(lessons)) blockers.push('the after-action names no lesson. Cite the L-ids recorded, or write "none" with the reason');
  }
  if (blockers.length) fail(`Cannot close ${run.topic} yet:\n${blockers.map((b) => `- ${b}`).join('\n')}`);
  run.status = 'closed';
  run.closed = today(env);
  saveRun(project, run);
  writeIndex(project);
  console.log(`closed ${run.topic}. Report: ${run.report}`);
}

export function paths({ cwd, env }) {
  const project = findProject(cwd);
  console.log(`shared memory: ${ensureGlobal(env)}`);
  if (!project) { console.log(`project: none (${CONFIG_NAME} not found; run \`pmr init\`)`); return; }
  console.log(`project: ${project.name} (${project.root})\nreports: ${relative(cwd, project.reportsDir) || '.'}\nworking files: ${relative(cwd, project.workDir) || '.'}\nproject context: ${project.contextFile ? relative(cwd, project.contextFile) : 'none (set context_file in the config)'}\nreport language: ${project.language} · refresh after ${project.refreshDays} days`);
}
